const seedProducts = async () => {
  try {
    console.log('Database connected');

    const categoryNames = [...new Set(products.map((product) => product[1]))];
    const categoryDocuments = await prisma.category.findMany({
      where: { name: { in: categoryNames } },
      select: { _id: true, name: true },
    });

    const categoryMap = new Map(
      categoryDocuments.map((category) => [category.name, category._id]),
    );

    const missingCategories = categoryNames.filter(
      (categoryName) => !categoryMap.has(categoryName),
    );

    if (missingCategories.length > 0) {
      throw new Error(
        `Missing categories: ${missingCategories.join(', ')}. Run "pnpm seed:categories" first.`,
      );
    }

    // Postgres enforces the products.user_id foreign key, unlike Mongo
    // (which happily stored a hardcoded ObjectId even if it didn't belong
    // to a real document). Resolve/seed a real owner user instead.
    let owner = await prisma.user.findFirst({ orderBy: { createdAt: 'asc' } });
    if (!owner) {
      owner = await prisma.user.create({
        data: {
          name: 'Seed Admin',
          email: 'seed-admin@ai-ecommerce.local',
          // Placeholder bcrypt hash for a seed-only account; change the
          // password via the API before using this account for anything.
          password:
            '$2a$10$C6UzMDM.H6dfI/f/IKcEeOoOCn.7VP5.gnPmuXOAr7YkTgUPGQPKa',
          role: 'admin',
        },
      });
      console.log(
        `No users found - created seed owner user (${owner.email})`,
      );
    }

    await prisma.product.deleteMany({});
    console.log('Existing products cleared');

    const productDocuments = products.map(
      ([
        name,
        category,
        description,
        image,
        originalPrice,
        discountPercent,
        stockCount,
        unit,
        isActive,
      ]) => ({
        userId: owner!._id,
        categoryId: categoryMap.get(category)!,
        name,
        slug: slugify(name, { lower: true, strict: true }),
        description,
        images: [image],
        originalPrice,
        salePrice:
          discountPercent > 0
            ? calculateSalePrice(originalPrice, discountPercent)
            : originalPrice,
        discountPercent,
        ...(discountPercent > 0
          ? { discountLabel: `${discountPercent}% OFF` }
          : {}),
        stockCount,
        unit,
        isActive,
        ratingAverage: 0,
        reviewCount: 0,
      }),
    );

    const created = await prisma.product.createMany({
      data: productDocuments,
      skipDuplicates: true,
    });
    console.log(`${created.count} products seeded successfully`);

    process.exit(0);
  } catch (error) {
    console.error('Seed failed:', error);
    process.exit(1);
  }
};

seedProducts();
